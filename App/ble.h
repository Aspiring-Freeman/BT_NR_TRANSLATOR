/**
 * @file    ble.h
 * @brief   蓝牙应用层 — 威星 1P / DS809 BLE 模组管理
 *
 * ============================================================================
 *  模组工作原理 (摘自 V1.20 用户手册)
 * ============================================================================
 *  · 模组是 BLE 从机 (Peripheral)，被手机 App 连接
 *  · 模组本身不存储参数：每次上电都会主动向 MCU 索要 MAC/密码/设备名/UUID
 *  · 5 次请求 (每次间隔 100ms) 都没收到 MCU 回复 → 模组使用芯片烧录的默认值
 *
 *  上电握手时序:
 *    ┌──────┐                          ┌────────┐
 *    │ MCU  │                          │ 模组   │
 *    └──┬───┘                          └────┬───┘
 *       │                                   │ ① 上电 (~100ms)
 *       │   ◄── B007 请求工作参数 ─────────│
 *       │   ── B007 响应 (MAC+PSW+Name) ──►│   ②  100ms 内回复
 *       │   ◄── B00D 请求 UUID 配置 ───────│
 *       │   ── B00D 响应 (默认/自定义) ───►│
 *       │                                   │ ③ 开始广播 ADV_IND
 *
 * ============================================================================
 *  本模块职责
 * ============================================================================
 *  1. 初始化时向 ProtocolManager 注册设备侧协议、绑定 UART 发送函数
 *  2. 注册事件回调，将协议帧转化为应用状态 (连接标志、缓存 MAC/版本)
 *  3. 自动响应模组上电请求 (B007/B00D) — 这是必须做的
 *  4. 提供周期性 BLE_Task() 监控握手是否成功，必要时主动查询模组状态
 *  5. 向上层暴露简洁的 API
 *
 * ============================================================================
 *  调用顺序
 * ============================================================================
 *    System_Init();            // 时钟、SysTick
 *    Peripheral_Init();        // GPIO / UART / ProtocolManager
 *    BLEUart_Init();           // 蓝牙 UART4 中断使能 (在 Peripheral_Init 内)
 *    BLE_SetDeviceName(...);   // 可选：覆盖默认设备名
 *    BLE_SetMacAddress(...);   // 可选：覆盖默认 MAC (建议用 MCU UID 派生)
 *    BLE_INIT();               // 注册回调 — 必须放最后
 *
 *    while(1) { BLE_Task(); ... }
 */
#ifndef __BLE_H__
#define __BLE_H__

#include <stdbool.h>
#include <stdint.h>

/*============================================================================
 *  配置 (可选，必须在 BLE_INIT() 之前调用才能在握手时生效)
 *===========================================================================*/

/**
 * @brief 设置 B007 响应中的 MAC 地址 (高位在前，与手机 App 显示顺序一致)
 * @param mac  6 字节 MAC，例如 {0xF4,0xD2,0x8B,0x8C,0x0F,0xB8}
 *
 * @note  若未调用，使用全 0 默认值，模组会回退到芯片烧录的随机静态地址
 *        (FF:xx:xx:xx:xx:xx 形式)。生产环境建议用 MCU UID 派生。
 */
void BLE_SetMacAddress(const uint8_t mac[6]);

/**
 * @brief 设置 B007 响应中的设备广播名 (≤8 字节)
 * @param name  设备名 (无需 \0 结尾)
 * @param len   长度 (>8 会被截断)
 *
 * @note  默认 "BT-FT"。手机 App 扫描时显示的就是这个名字。
 */
void BLE_SetDeviceName(const char *name, uint8_t len);

/**
 * @brief 设置 B007 响应中的配对密码 (4 字节小端整数)
 * @param password  4 字节，例如 123456 → {0x40,0xE2,0x01,0x00}
 *                  全 0xFF 表示不设密码
 */
void BLE_SetPairingPassword(const uint8_t password[4]);

/*============================================================================
 *  初始化 & 任务
 *===========================================================================*/

/**
 * @brief 蓝牙应用层初始化
 *
 * 完成的工作:
 *   ① 注册 DS809 协议到 ProtocolManager 的设备槽位
 *   ② 绑定 UART4 发送函数 (BLEUart_Tx_Send)
 *   ③ 注册协议事件回调，准备接收模组的 B007/B00D 请求
 *   ④ 启动握手监控状态机
 *
 * 必须在 BLEUart_Init() 之后调用。返回后即可被模组主动握手。
 */
void BLE_INIT(void);

/**
 * @brief 蓝牙周期任务 (建议每次主循环都调用，开销极小)
 *
 * 内部职责:
 *   · 监控上电握手是否在 3 秒内完成；超时则告警 (通常意味着 UART 接反/没通)
 *   · 握手成功后主动查询固件版本、实际 MAC 地址，缓存供上层读取
 */
void BLE_Task(void);

/*============================================================================
 *  状态查询 (运行时只读接口)
 *===========================================================================*/

/** @brief 蓝牙是否已与手机 App 连接 */
bool BLE_IsConnected(void);

/** @brief 是否完成上电握手 (B007 已应答) */
bool BLE_IsReady(void);

/**
 * @brief 读取缓存的实际启用 MAC 地址 (来自 0xC001 查询)
 * @param mac_out  输出缓冲区, 6 字节, 高位在前
 * @return true=已获取, false=尚未查询到
 */
bool BLE_GetMacAddress(uint8_t mac_out[6]);

/**
 * @brief 读取缓存的模组固件版本 (来自 0xB011 查询)
 * @return true=已获取
 */
bool BLE_GetFirmwareVersion(uint8_t *major, uint8_t *minor, uint8_t *patch);

/*============================================================================
 *  BLE 接收数据分发 (供 main.c 调用)
 *===========================================================================*/

/**
 * @brief 处理一帧来自 BLE 模组的 RX 数据
 *
 * 内部并行喂入两个协议解析器:
 *   ① DS809 (ProtocolManager_Device_Parse) — 处理 B007/B00D 握手与查询应答
 *   ② bt_app_protocol — 处理 APP 应用层 BB01/BB02/AAFF 帧
 *
 * 两者同时识别各自的帧头，互不干扰。
 */
void BLE_OnRxData(uint8_t *buf, uint16_t len);

#endif /* __BLE_H__ */
